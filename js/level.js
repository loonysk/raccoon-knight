/* дуга монет */
function coinArc(x0, y0, n, dx, lift) {
  const a = [];
  for (let i = 0; i < n; i++) {
    const t = n > 1 ? i / (n - 1) : .5;
    a.push({ x: Math.round(x0 + i * dx), y: Math.round(y0 - Math.sin(t * Math.PI) * (lift || 0)) });
  }
  return a;
}
/* ряд монет */
function coinRow(x0, y, n, dx) { return coinArc(x0, y, n, dx, 0); }

